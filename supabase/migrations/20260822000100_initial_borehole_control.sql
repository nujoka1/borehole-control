create or replace function public.audit_borehole_command()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.borehole_events (
    device_id, event_type, message, actor_user_id, metadata
  ) values (
    new.device_id,
    case new.command_type
      when 'set_config' then 'configuration_requested'
      when 'set_mode' then 'mode_requested'
      when 'clear_fault' then 'fault_clear_requested'
      else 'manual_pump_requested'
    end,
    'Dashboard command requested',
    new.requested_by,
    jsonb_build_object('command_id', new.id, 'command_type', new.command_type)
  );
  return new;
end;
$$;

revoke all on function public.audit_borehole_command() from public;
create trigger audit_borehole_command_insert
  after insert on public.borehole_commands
  for each row execute function public.audit_borehole_command();
