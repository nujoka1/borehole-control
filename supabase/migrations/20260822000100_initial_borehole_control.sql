  public.borehole_events_id_seq to authenticated;

create policy "users read their profile" on public.borehole_profiles
  for select to authenticated using (user_id = (select auth.uid()));
create policy "users create their profile" on public.borehole_profiles
  for insert to authenticated with check (user_id = (select auth.uid()));
create policy "users update their profile" on public.borehole_profiles
  for update to authenticated using (user_id = (select auth.uid()))
  with check (user_id = (select auth.uid()));

create policy "members read their devices" on public.borehole_devices
  for select to authenticated using (exists (
    select 1 from public.borehole_device_members m
    where m.device_id = id and m.user_id = (select auth.uid())
  ));
create policy "members read their memberships" on public.borehole_device_members
  for select to authenticated using (user_id = (select auth.uid()));
create policy "members read device settings" on public.borehole_device_settings
  for select to authenticated using (exists (
    select 1 from public.borehole_device_members m
    where m.device_id = borehole_device_settings.device_id
      and m.user_id = (select auth.uid())
  ));
create policy "members read device telemetry" on public.borehole_readings
  for select to authenticated using (exists (
    select 1 from public.borehole_device_members m
    where m.device_id = borehole_readings.device_id
      and m.user_id = (select auth.uid())
  ));
create policy "members read device commands" on public.borehole_commands
  for select to authenticated using (exists (
    select 1 from public.borehole_device_members m
    where m.device_id = borehole_commands.device_id
      and m.user_id = (select auth.uid())
  ));
create policy "owners and operators create device commands" on public.borehole_commands
  for insert to authenticated with check (
    requested_by = (select auth.uid()) and exists (
      select 1 from public.borehole_device_members m
      where m.device_id = borehole_commands.device_id
        and m.user_id = (select auth.uid())
        and m.role in ('owner', 'operator')
    )
  );
create policy "members read latest device state" on public.borehole_device_state
  for select to authenticated using (exists (
    select 1 from public.borehole_device_members m
    where m.device_id = borehole_device_state.device_id
      and m.user_id = (select auth.uid())
  ));
create policy "members read device events" on public.borehole_events
  for select to authenticated using (exists (
    select 1 from public.borehole_device_members m
    where m.device_id = borehole_events.device_id
      and m.user_id = (select auth.uid())
  ));

